#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
RS485_C 最大末端設備數量計算（含層數）
====================================================================
問題：這套多層樹最多能接幾台末端設備？跟層數的關係？

定址前提（見 docs/03、docs/06 A1）：
  - 每台用 6-bit 指撥 → 本地位址 0..63。
  - 位址 0 保留給廣播 → 每條 bus 實際可用 1..63 = 63 台。
  - 分層位址是字串（1-32-4…），長度不限 → 層數理論上無上限。

樹的算法：要「末端數最大」，就讓每個非葉節點都當中繼器(繼續分支)、
只有最底層當末端。深度 D 層 bus 時：
  - 第 1..D-1 層：每個節點都是中繼器，每台底下再開一條 63 台的 bus。
  - 第 D 層：全是末端。
  → 末端總數 = 63^D
  → 中繼器數 = 63^1 + 63^2 + … + 63^(D-1) = (63^D - 63) / 62
"""

USABLE = 63          # 每條 bus 可用位址數（0 保留廣播）
FULL = 64            # 若不保留 0（需另設廣播機制）


def terminals(base, depth):
    return base ** depth


def repeaters(base, depth):
    return sum(base ** k for k in range(1, depth))   # 第 1..depth-1 層


def main():
    print("=" * 70)
    print("RS485_C 最大末端設備數量（每條 bus 可用 %d 台，0 保留廣播）" % USABLE)
    print("=" * 70)
    print("\n%-4s | %-18s | %-18s | %s" %
          ("層數D", "最大末端數 63^D", "需要中繼器數", "全樹節點總數"))
    print("-" * 70)
    for D in range(1, 7):
        t = terminals(USABLE, D)
        r = repeaters(USABLE, D)
        print("%-5d | %18s | %18s | %s"
              % (D, "{:,}".format(t), "{:,}".format(r), "{:,}".format(t + r)))

    print("\n對照：若不保留位址 0（滿 64/ bus，但要另設廣播機制）")
    print("-" * 70)
    for D in range(1, 7):
        print("  D=%d → 最大末端 %s" % (D, "{:,}".format(terminals(FULL, D))))

    print("\n" + "=" * 70)
    print("重點結論")
    print("=" * 70)
    print("""
  1. 定址上限是「指數成長」：每加一層，末端上限 ×63。
       1 層 = 63 台；2 層 ≈ 3,969；3 層 ≈ 25 萬；4 層 ≈ 1,575 萬；5 層 ≈ 9.9 億。
     字串位址長度不限 → 定址本身幾乎不是瓶頸。

  2. 真正的上限不是定址，是「輪詢新鮮度」與工程現實：
     - 新鮮度：每條 bus 的中繼器 round-robin 輪完 63 台約需
         63 × (請求+回覆+逾時裕度) ≈ 63 × ~6ms ≈ 0.4 秒/圈（@115200）。
       但 cache 樹把各層「解耦」：每條 bus 只顧自己這圈，PC 隨時拿 cache，
       所以「葉端新鮮度」約等於它那條 bus 的一圈時間（~0.4s），
       不會因為整棵樹變大而線性惡化——這正是 cache 樹的價值。
     - 頂層頻寬：樹很大時，PC 從第 1 層那條鏈拉「整包 cache」會變大，
       這才是先撞到的牆 → 上模組 F 把頂層鏈路換 Ethernet/WiFi。
     - 電氣：一條 bus 掛 63 台需低單位負載收發器；MAX13487(1/4 UL)
       電氣上可到 ~128 台，遠高於 63 位址上限，不是限制。
     - 佈線/供電/現場調機：實務上單條 bus 掛滿 63 台已偏多，
       多半用「較淺但較寬」或「適度分層」的折衷。

  3. 實務建議：定址容量遠超需求，設計時以「新鮮度需求 + 頂層頻寬 +
     佈線可行性」反推層數與每層寬度，而不是去逼近 63^D 的理論極限。
""")


if __name__ == "__main__":
    main()
